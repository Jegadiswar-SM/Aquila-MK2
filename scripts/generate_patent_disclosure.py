def clean_text_for_pdf(md: str) -> List[str]:
    lines: List[str] = []
    for raw in md.splitlines():
        line = raw.strip()
        if not line or line == "\\pagebreak":
            lines.append("")
            continue
        if line.startswith("!["):
            continue
        line = re.sub(r"!\[[^\]]*\]\([^)]+\)", "", line)
        line = re.sub(r"\[([^\]]+)\]\([^)]+\)", r"\1", line)
        line = line.replace("**", "").replace("*", "")
        line = line.replace("`", "")
        line = line.replace("|", " | ")
        line = line.replace("→", "->").replace("≈", "~").replace("×", "x")
        line = line.replace("−", "-").replace("‑", "-").replace("–", "-")
        lines.append(line)
    return lines


